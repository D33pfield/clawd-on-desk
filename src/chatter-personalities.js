// Flat shape the prompt builder uses: `examples` is the plain text list and
// `exampleFocus` maps each line to the focus keys it was written for.
const PERSONALITIES = Object.freeze(Object.fromEntries(Object.entries(DEFINITIONS).map(([id, def]) => [
  id,
  Object.freeze({
    label: def.label,
    persona: `You are Clawd, a small orange pixel creature living on the desktop. ${def.persona}`,
    rules: def.rules,
    examples: Object.freeze(def.examples.map(([text]) => text)),
    exampleFocus: new Map(def.examples.map(([text, focus]) => [text, focus])),
  }),
])));

const PERSONALITY_IDS = Object.freeze(Object.keys(PERSONALITIES));
const DEFAULT_PERSONALITY = "deadpan";

module.exports = { PERSONALITIES, PERSONALITY_IDS, DEFAULT_PERSONALITY };
